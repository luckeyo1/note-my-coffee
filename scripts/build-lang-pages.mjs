// scripts/build-lang-pages.mjs
// ──────────────────────────────────────────────────────────────────────────
// 언어별 정적 랜딩 페이지 생성기: index.html → en.html / ja.html / zh.html.
//
// 왜 필요한가: 랜딩은 한 URL(index.html)에서 JS(landing-i18n.js)로 번역을 교체한다.
// 사람은 잘 보지만, 검색엔진 색인·카카오톡/트위터/레딧 링크 미리보기는 "정적 HTML"을
// 읽으므로 언어와 무관하게 한국어 head·OG만 본다. 그래서 각 언어를 실제 정적 파일로
// 구워 /en·/ja·/zh 에 서빙한다(self-canonical + 언어별 OG + 공통 hreflang).
//
// 방식: index.html?lang=<code> 를 헤드리스로 열어 landing-i18n.js가 head·본문을 그
// 언어로 바꾼 상태를 스냅샷한다. 브라우저 안에서 canonical·og:url·구조화데이터(ld+json)를
// 그 언어로 바로잡은 뒤 직렬화해 저장한다. (스냅샷을 정규식으로 고치지 않으려고 보정은
// 브라우저 DOM에서 먼저 한다.)
//
// 실행:  (repo 루트에서 http.server 8914 띄운 뒤)  node scripts/build-lang-pages.mjs
// ⚠️ 랜딩 카피(index.html)나 사전(landing-i18n.js)을 바꾸면 이 스크립트를 다시 돌려야
//    언어 페이지가 동기화된다.
import pkg from '/opt/node22/lib/node_modules/playwright/index.js';
const { chromium } = pkg;
import fs from 'fs';

const ROOT = '/home/user/note-my-coffee';
const BASE = 'https://note-my-coffee.web.app';
const PORT = process.env.PORT || 8914;
const LANGS = [
  { code: 'en', path: '/en', file: 'en.html' },
  { code: 'ja', path: '/ja', file: 'ja.html' },
  { code: 'zh', path: '/zh', file: 'zh.html' },
];

// ── landing-i18n.js에서 번역 사전 P를 그대로 가져온다(ld+json 재구성용) ──
const src = fs.readFileSync(ROOT + '/landing-i18n.js', 'utf8');
const s0 = src.indexOf('var P = {');
const s1 = src.indexOf('\n    };', s0);
const P = eval('(' + src.slice(s0 + 'var P = '.length, s1 + 6) + ')');
const tr = (key, l) => { const m = P[key]; return m ? (m[l] != null ? m[l] : m.en) : ''; };
const clean = (x) => String(x || '').replace(/\s+/g, ' ').trim();

// 구조화데이터에만 쓰는 짧은 문구(본문엔 없음).
const INLANG = { en: 'en', ja: 'ja', zh: 'zh-Hant' };
const BROWSER_REQ = {
  en: 'Modern browser (no install required)',
  ja: '最新のブラウザ（インストール不要）',
  zh: '現代瀏覽器（免安裝）',
};
const FEATURES = {
  en: ['Log espresso & hand-drip recipes', 'Real-time SCA extraction feedback', 'Built-in stopwatch', 'Recipe logbook by bean and date', 'Cross-device sync'],
  ja: ['エスプレッソ・ハンドドリップのレシピ記録', 'SCA基準のリアルタイム抽出フィードバック', '内蔵ストップウォッチ', '豆別・日付別のレシピログブック', '端末間同期'],
  zh: ['記錄義式濃縮與手沖食譜', '依 SCA 的即時萃取回饋', '內建碼錶', '依豆子與日期的食譜筆記本', '跨裝置同步'],
};

function ldjson(l, url) {
  const faq = (q, a) => ({ '@type': 'Question', name: clean(tr(q, l)), acceptedAnswer: { '@type': 'Answer', text: clean(a) } });
  const obj = {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'SoftwareApplication',
        name: 'Note My Coffee',
        url: url,
        applicationCategory: 'LifestyleApplication',
        operatingSystem: 'Any',
        browserRequirements: BROWSER_REQ[l],
        inLanguage: INLANG[l],
        image: BASE + '/og-image.png',
        description: clean(tr('head.desc', l)),
        featureList: FEATURES[l],
        offers: { '@type': 'Offer', price: '0', priceCurrency: 'KRW' },
      },
      {
        '@type': 'FAQPage',
        mainEntity: [
          faq('faq.q1', tr('faq.a1_main', l) + tr('faq.a1_support', l)),
          faq('faq.q2', tr('faq.a2', l)),
          faq('faq.q3', tr('faq.a3', l)),
          faq('faq.q4', tr('faq.a4', l)),
        ],
      },
    ],
  };
  return JSON.stringify(obj, null, 2);
}

const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
let wrote = 0;
try {
  for (const L of LANGS) {
    const url = BASE + L.path;
    const ctx = await browser.newContext();
    const page = await ctx.newPage();
    // Firebase CDN(gstatic) 차단 요청은 조용히 무시 — landing.js(모듈)는 못 돌지만
    // landing-i18n.js(classic)와 인라인 퀴즈는 돌아 head·본문·퀴즈가 번역된다.
    await page.goto(`http://127.0.0.1:${PORT}/index.html?lang=${L.code}`, { waitUntil: 'domcontentloaded' });
    await page.waitForTimeout(700);

    // 브라우저 DOM에서 언어별 보정(직렬화 전) — canonical·og:url·ld+json.
    await page.evaluate(({ url, ld }) => {
      const can = document.querySelector('link[rel="canonical"]'); if (can) can.setAttribute('href', url);
      const ogu = document.querySelector('meta[property="og:url"]'); if (ogu) ogu.setAttribute('content', url);
      const sd = document.querySelector('script[type="application/ld+json"]'); if (sd) sd.textContent = ld;
      // ?lang= 쿼리는 정적 파일엔 불필요 — 혹시 남은 흔적 정리는 생략(본문엔 없음).
    }, { url, ld: ldjson(L.code, url) });

    const marker = `<!-- GENERATED by scripts/build-lang-pages.mjs — 직접 수정하지 마세요.\n     원본은 index.html + landing-i18n.js. 그 둘을 바꾸면 이 스크립트를 다시 돌려 동기화. -->\n`;
    const html = (await page.content()).replace('<!DOCTYPE html>', '<!DOCTYPE html>\n' + marker);
    fs.writeFileSync(`${ROOT}/${L.file}`, html);
    console.log(`✓ ${L.file}  (${(html.length / 1024).toFixed(0)} KB)  lang=${L.code} canonical=${url}`);
    wrote++;
    await ctx.close();
  }
} finally {
  await browser.close();
}
console.log(wrote === LANGS.length ? `\n완료: ${wrote}개 언어 페이지 생성` : `\n경고: ${wrote}/${LANGS.length}개만 생성`);
process.exit(wrote === LANGS.length ? 0 : 1);
